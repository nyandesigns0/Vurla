import { readFileSync, writeFileSync } from "node:fs";
import { deflateSync } from "node:zlib";
import { GRAIN_CELL, GRAIN_TILE_SIZE, grainCell } from "../src/components/site/grain-pattern.mjs";

const tokens = readFileSync(new URL("../src/lib/design-system/tokens.ts", import.meta.url), "utf8");
const paper = tokens.match(/paper:\s*"(#[\da-f]{6})"/i)?.[1];
if (!paper) throw new Error("Paper color token not found");
const rgb = [1, 3, 5].map(offset => parseInt(paper.slice(offset, offset + 2), 16));
function chunk(type, data) {
  const bytes = Buffer.concat([Buffer.from(type), data]);
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
  }
  const prefix = Buffer.alloc(4), suffix = Buffer.alloc(4);
  prefix.writeUInt32BE(data.length);
  suffix.writeUInt32BE((crc ^ 0xffffffff) >>> 0);
  return Buffer.concat([prefix, bytes, suffix]);
}
const header = Buffer.alloc(13);
header.writeUInt32BE(GRAIN_TILE_SIZE, 0);
header.writeUInt32BE(GRAIN_TILE_SIZE, 4);
header[8] = 1; // One-bit indexed pixels: transparent or paper at 128/255 alpha.
header[9] = 3;
const stride = 1 + GRAIN_TILE_SIZE / 8;
const rows = Buffer.alloc(stride * GRAIN_TILE_SIZE);
for (let y = 0; y < GRAIN_TILE_SIZE; y++) {
  for (let x = 0; x < GRAIN_TILE_SIZE; x++) {
    if (grainCell(x, y)) rows[y * stride + 1 + (x >> 3)] |= 1 << (7 - (x & 7));
  }
}
const png = Buffer.concat([
  Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", header),
  chunk("PLTE", Buffer.from([0, 0, 0, ...rgb])), chunk("tRNS", Buffer.from([0, 128])),
  chunk("IDAT", deflateSync(rows)), chunk("IEND", Buffer.alloc(0)),
]);
const css = `/* Generated by scripts/generate-grain-tile.mjs; shares the canvas seed and paper token. */
.grain-texture {
  background-image: url("data:image/png;base64,${png.toString("base64")}");
  background-repeat: repeat;
  background-size: ${GRAIN_TILE_SIZE * GRAIN_CELL}px ${GRAIN_TILE_SIZE * GRAIN_CELL}px;
}
.grain-texture[data-grain-ready="true"] { background-image: none; }
.route-loading { position: relative; isolation: isolate; }
.route-loading > .grain-texture { z-index: -1; }
`;
const output = new URL("../src/components/site/grain-texture.css", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8").replaceAll("\r\n", "\n") !== css) throw new Error("Grain CSS is stale; run node scripts/generate-grain-tile.mjs");
} else {
  writeFileSync(output, css);
}
